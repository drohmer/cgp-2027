#!/usr/bin/env python3
"""
Scan cgp/ modules for test_*.hpp files, extract cgp_test:: function
declarations, and generate the test main.cpp that calls all of them.

Usage: generate_main.py <cgp_dir> <output_main.cpp>
"""

import sys
import re
from pathlib import Path

# Pure-math modules only — no OpenGL/GLFW dependency
INCLUDE_MODULES = [
    "01_base",
    "02_numarray",
    "03_files",
    "04_grid_container",
    "05_vec",
    "06_mat",
    "08_random_noise",
    "09_geometric_transformation",
    "10_camera_model",
    "11_mesh",
    "12_shape",
    # Module 17 is GL-free once its clock is abstracted (timer_set_time_source).
    "17_timer",
    # Modules 13+ depend on OpenGL/GLFW and are excluded. The two entries below
    #  are scanned only for their GL-free sub-parts (obj loader, path helper);
    #  the matching CMake GLOB compiles just those sub-directories.
    "20_format_parser",
    "21_scene_project_helper",
]


def find_test_headers(cgp_dir):
    headers = []
    for module in INCLUDE_MODULES:
        module_path = cgp_dir / module
        if module_path.exists():
            headers.extend(sorted(module_path.rglob("test_*.hpp")))
    return headers


def extract_test_functions(header_path):
    """Return list of void function names declared inside namespace cgp_test."""
    content = header_path.read_text()
    functions = []
    for block in re.findall(r'namespace\s+cgp_test\s*\{([^}]*)\}', content):
        functions.extend(re.findall(r'void\s+(\w+)\s*\(\s*\)\s*;', block))
    return functions


def generate(cgp_dir, output_path):
    project_root = cgp_dir.parent
    includes = []
    calls = []

    for header in find_test_headers(cgp_dir):
        functions = extract_test_functions(header)
        if not functions:
            continue
        rel = header.relative_to(project_root).as_posix()
        includes.append(f'#include "{rel}"')
        for fn in functions:
            calls.append(f'    cgp_test::{fn}();')

    lines = [
        "// Auto-generated by test/generate_main.py — do not edit manually",
        "#include <iostream>",
        "",
        *includes,
        "",
        "int main()",
        "{",
        *calls,
        '    std::cout << "All tests passed." << std::endl;',
        "    return 0;",
        "}",
        "",
    ]

    output_path.write_text("\n".join(lines))
    print(f"Generated {output_path} ({len(calls)} test calls)")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        print(f"Usage: {sys.argv[0]} <cgp_dir> <output_main.cpp>")
        sys.exit(1)
    generate(Path(sys.argv[1]), Path(sys.argv[2]))
